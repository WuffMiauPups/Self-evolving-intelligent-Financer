"""Plain data types returned by the GUI service layer.

These are intentionally serializable, framework-free dataclasses so the GUI
never has to deal with backend internals (torch tensors, pydantic models, etc).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Any

import yaml


class RuntimeState(str, Enum):
    STOPPED = "stopped"
    STARTING = "starting"
    RUNNING = "running"
    STOPPING = "stopping"
    ERROR = "error"


@dataclass
class RuntimeOverrides:
    """Per-run overrides captured from the GUI and emitted as a layered YAML.

    Only fields that are non-None are written to disk, so the override file
    stays minimal and the config deep-merge in ``src/core/config.py`` only
    touches what the operator actually changed.  The file is passed as the
    final ``--config`` argument in runtime/backtest/training subprocess
    commands (later files override earlier files).
    """

    # --- runtime toggles ---
    frozen_brain: bool | None = None           # True = frozen weights; False = allow online updates
    memory_enabled: bool | None = None
    memory_updates_enabled: bool | None = None
    # --- memory caps ---
    max_memory_items: int | None = None
    # --- training/calibration toggles ---
    platt_calibration_enabled: bool | None = None
    separate_risk_heads: bool | None = None
    # --- checkpoint selection ---
    checkpoint_path: str | None = None

    def to_yaml_dict(self) -> dict[str, Any]:
        """Return a nested dict mapping only the set fields into AppConfig paths.

        None-valued fields are skipped entirely so the override YAML does not
        accidentally clobber whatever the preset/default YAMLs declared.
        """
        out: dict[str, Any] = {}
        runtime: dict[str, Any] = {}
        memory: dict[str, Any] = {}
        model: dict[str, Any] = {}
        training: dict[str, Any] = {}

        if self.frozen_brain is not None:
            runtime["allow_online_model_updates"] = not bool(self.frozen_brain)
        if self.memory_updates_enabled is not None:
            runtime["allow_online_memory_updates"] = bool(self.memory_updates_enabled)
        if self.memory_enabled is not None:
            memory["enabled"] = bool(self.memory_enabled)
        if self.max_memory_items is not None:
            memory["max_items"] = int(self.max_memory_items)
        if self.platt_calibration_enabled is not None:
            training["platt_calibration_enabled"] = bool(self.platt_calibration_enabled)
        if self.separate_risk_heads is not None:
            model["separate_risk_heads"] = bool(self.separate_risk_heads)
        if self.checkpoint_path is not None:
            model["checkpoint_path"] = str(self.checkpoint_path)

        if runtime:
            out["runtime"] = runtime
        if memory:
            out["memory"] = memory
        if model:
            out["model"] = model
        if training:
            out["training"] = training
        return out

    def write_yaml(self, path: Path | str) -> Path:
        """Write the override dict to a YAML file (creating parent dirs)."""
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        data = self.to_yaml_dict()
        header = (
            "# Auto-generated by the SETAI GUI. Do not edit by hand — it will be\n"
            "# overwritten on the next Start.  Only fields toggled in the GUI are\n"
            "# present here; everything else inherits from default.yaml.\n"
        )
        with open(p, "w", encoding="utf-8") as f:
            f.write(header)
            if data:
                yaml.safe_dump(data, f, sort_keys=False, default_flow_style=False)
        return p

    def is_empty(self) -> bool:
        return not self.to_yaml_dict()


@dataclass
class RuntimeStatus:
    state: RuntimeState = RuntimeState.STOPPED
    pid: int | None = None
    started_at: datetime | None = None
    last_log_timestamp: datetime | None = None
    last_message: str = ""
    symbols: list[str] = field(default_factory=list)
    frozen_brain: bool = True
    memory_enabled: bool = False
    memory_updates_enabled: bool = False
    last_decision_summary: str = ""
    last_risk_decision_summary: str = ""
    # EV gate status (Phase 5/7 — feeds the "is this trade worth it?" check)
    ev_gate_active: bool = False          # True when the risk head is trained (separate_risk_heads)
    ev_cost_bps: float = 0.0              # fee_bps + slippage_bps (cost side of the EV gate)
    platt_calibration_enabled: bool = False
    # True when platt_calibration.json exists next to the configured
    # checkpoint (platt_calibration_path_for_checkpoint) — the artifact is
    # checkpoint-bound, not the legacy runs/platt_calibration.json.
    platt_calibration_fitted: bool = False
    error_message: str = ""


@dataclass
class BacktestResultRow:
    timestamp: datetime
    label: str
    total_return: float
    max_drawdown: float
    win_rate: float
    turnover: float
    fill_count: int
    profit_factor: float = 0.0
    expectancy: float = 0.0
    avg_return_per_trade: float = 0.0
    sharpe_ratio: float = 0.0
    sortino_ratio: float = 0.0
    avg_exposure: float = 0.0
    round_trip_win_rate: float = 0.0
    config_paths: list[str] = field(default_factory=list)
    notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "timestamp": self.timestamp.isoformat(),
            "label": self.label,
            "total_return": self.total_return,
            "max_drawdown": self.max_drawdown,
            "win_rate": self.win_rate,
            "turnover": self.turnover,
            "fill_count": self.fill_count,
            "profit_factor": self.profit_factor,
            "expectancy": self.expectancy,
            "avg_return_per_trade": self.avg_return_per_trade,
            "sharpe_ratio": self.sharpe_ratio,
            "sortino_ratio": self.sortino_ratio,
            "avg_exposure": self.avg_exposure,
            "round_trip_win_rate": self.round_trip_win_rate,
            "config_paths": list(self.config_paths),
            "notes": self.notes,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "BacktestResultRow":
        return cls(
            timestamp=datetime.fromisoformat(data["timestamp"]),
            label=data.get("label", ""),
            total_return=float(data.get("total_return", 0.0)),
            max_drawdown=float(data.get("max_drawdown", 0.0)),
            win_rate=float(data.get("win_rate", 0.0)),
            turnover=float(data.get("turnover", 0.0)),
            fill_count=int(data.get("fill_count", 0)),
            profit_factor=float(data.get("profit_factor", 0.0)),
            expectancy=float(data.get("expectancy", 0.0)),
            avg_return_per_trade=float(data.get("avg_return_per_trade", 0.0)),
            sharpe_ratio=float(data.get("sharpe_ratio", 0.0)),
            sortino_ratio=float(data.get("sortino_ratio", 0.0)),
            avg_exposure=float(data.get("avg_exposure", 0.0)),
            round_trip_win_rate=float(data.get("round_trip_win_rate", 0.0)),
            config_paths=list(data.get("config_paths", [])),
            notes=data.get("notes", ""),
        )


